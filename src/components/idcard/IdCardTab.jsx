// ===== Gen ID Card (ใช้สำหรับทดสอบเท่านั้น) =====
import { useCallback, useEffect, useRef, useState } from "react";
import defaultAvatarUrl from "../../assets/default-avatar.jpg";
import { formatThaiId, isValidThaiId, randomThaiId } from "../../lib/thaiId.js";

const W = 1012;
const H = 638;
const FONT = `"Sarabun", "Noto Sans Thai", Tahoma, sans-serif`;

function loadImage(src, useCors) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    if (useCors) img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error("โหลดรูปไม่สำเร็จ"));
    img.src = src;
  });
}

// ครอปรูปแบบ object-fit: cover ให้เต็มกรอบโดยไม่บิดสัดส่วน
function drawCover(ctx, img, x, y, w, h) {
  const scale = Math.max(w / img.width, h / img.height);
  const sw = w / scale, sh = h / scale;
  const sx = (img.width - sw) / 2, sy = (img.height - sh) / 2;
  ctx.drawImage(img, sx, sy, sw, sh, x, y, w, h);
}

// วางชื่อตัวใหญ่สีแดงกลางรูป (ย่อขนาดอัตโนมัติให้พอดีกรอบ)
function drawNameOnPhoto(ctx, text, x, y, w, h) {
  if (!text) return;

  const maxWidth = w - 24;
  let size = 96;

  ctx.save();
  ctx.font = `900 ${size}px ${FONT}`;
  while (ctx.measureText(text).width > maxWidth && size > 28) {
    size -= 4;
    ctx.font = `900 ${size}px ${FONT}`;
  }

  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  const cx = x + w / 2, cy = y + h / 2;

  ctx.lineWidth = Math.max(4, size / 8);
  ctx.lineJoin = "round";
  ctx.strokeStyle = "#fff";
  ctx.strokeText(text, cx, cy, maxWidth);

  ctx.fillStyle = "#d50000";
  ctx.fillText(text, cx, cy, maxWidth);

  ctx.restore();
}

function drawCard(canvas, fields, photoImg, defaultPhoto) {
  const ctx = canvas.getContext("2d");
  const digits = fields.number.replace(/\D/g, "").slice(0, 13);
  const firstTh = fields.firstTh.trim() || "ชื่อ";
  const lastTh  = fields.lastTh.trim()  || "นามสกุล";
  const firstEn = fields.firstEn.trim() || "First";
  const lastEn  = fields.lastEn.trim()  || "Last";

  // พื้นหลัง
  ctx.fillStyle = "#eef3fb";
  ctx.fillRect(0, 0, W, H);

  // แถบหัว (บอกชัดว่าเป็นของทดสอบ)
  ctx.fillStyle = "#c62828";
  ctx.fillRect(0, 0, W, 90);
  ctx.fillStyle = "#fff";
  ctx.font = `bold 40px ${FONT}`;
  ctx.textBaseline = "middle";
  ctx.textAlign = "left";
  ctx.fillText("TEST ONLY · บัตรทดสอบ ไม่ใช่เอกสารจริง", 36, 46);

  // เลขบัตร
  ctx.fillStyle = "#555";
  ctx.font = `26px ${FONT}`;
  ctx.fillText("เลขประจำตัว / ID No.", 36, 140);
  ctx.fillStyle = "#111";
  ctx.font = `bold 52px ${FONT}`;
  ctx.fillText(formatThaiId(digits), 36, 195);

  // ชื่อ
  const label = (t, y) => { ctx.fillStyle = "#555"; ctx.font = `26px ${FONT}`; ctx.fillText(t, 36, y); };
  const value = (t, y) => { ctx.fillStyle = "#111"; ctx.font = `bold 44px ${FONT}`; ctx.fillText(t, 36, y); };

  label("ชื่อ-นามสกุล", 270);   value(`${firstTh} ${lastTh}`, 318);
  label("Name",        390);   value(`${firstEn} ${lastEn}`, 438);

  // กรอบรูป (ขวา)
  const px = W - 300, py = 130, pw = 260, ph = 330;
  ctx.fillStyle = "#d5dce8";
  ctx.fillRect(px, py, pw, ph);
  const photo = photoImg || defaultPhoto;
  if (photo) {
    drawCover(ctx, photo, px, py, pw, ph);
    if (!photoImg) drawNameOnPhoto(ctx, fields.firstTh.trim(), px, py, pw, ph);
  } else {
    ctx.fillStyle = "#888";
    ctx.font = `24px ${FONT}`;
    ctx.textAlign = "center";
    ctx.fillText("ไม่มีรูป", px + pw / 2, py + ph / 2);
    ctx.textAlign = "left";
  }

  // ลายน้ำคาดทั้งใบ
  ctx.save();
  ctx.translate(W / 2, H / 2);
  ctx.rotate(-0.35);
  ctx.fillStyle = "rgba(198, 40, 40, 0.16)";
  ctx.font = `bold 120px ${FONT}`;
  ctx.textAlign = "center";
  ctx.fillText("SPECIMEN · TEST", 0, 0);
  ctx.restore();

  // ท้ายบัตร
  ctx.fillStyle = "#777";
  ctx.font = `22px ${FONT}`;
  ctx.textAlign = "left";
  ctx.fillText(`Generated by Sale Here STAR data tool · ${new Date().toLocaleDateString("th-TH")}`, 36, H - 36);
}

function numberHintFor(number) {
  const digits = number.replace(/\D/g, "").slice(0, 13);
  if (!digits.length) return "";
  if (digits.length < 13) return `ยังไม่ครบ (${digits.length}/13)`;
  return isValidThaiId(digits) ? "✅ checksum ถูกต้อง" : "⚠️ checksum ไม่ถูก (ระบบ KYC อาจไม่รับ)";
}

export default function IdCardTab({ active }) {
  const canvasRef = useRef(null);
  const fileInputRef = useRef(null);
  const lastUrlRef = useRef("");

  const [fields, setFields] = useState({
    number: "", firstTh: "", lastTh: "", firstEn: "", lastEn: "", photoUrl: ""
  });
  const [photoImg, setPhotoImg] = useState(null);       // รูปที่เลือก (ไฟล์/URL)
  const [defaultPhoto, setDefaultPhoto] = useState(null); // รูปตั้งต้น
  const [photoHint, setPhotoHint] = useState("");

  const setField = (name, value) => setFields(f => ({ ...f, [name]: value }));

  const draw = useCallback(() => {
    if (canvasRef.current) drawCard(canvasRef.current, fields, photoImg, defaultPhoto);
  }, [fields, photoImg, defaultPhoto]);

  // วาดใหม่ทุกครั้งที่ข้อมูลเปลี่ยน
  useEffect(() => { draw(); }, [draw]);

  // โหลดรูปตั้งต้น เสร็จแล้ววาดใหม่อีกรอบ
  useEffect(() => {
    loadImage(defaultAvatarUrl, false)
      .then(setDefaultPhoto)
      .catch(() => console.warn("โหลดรูปตั้งต้นไม่สำเร็จ:", defaultAvatarUrl));
  }, []);

  const onFileChange = async (e) => {
    const file = e.target.files[0];
    if (!file) {
      setPhotoImg(null);
      setPhotoHint("ใช้รูปตั้งต้น");
      return;
    }
    const url = URL.createObjectURL(file);
    const img = await loadImage(url, false);
    setPhotoImg(img);
    setField("photoUrl", "");
    lastUrlRef.current = "";
    setPhotoHint(`ใช้รูปจากไฟล์: ${file.name}`);
  };

  // เทียบเท่า event "change" ของ input URL เดิม (ทำงานตอน blur / Enter เมื่อค่าเปลี่ยน)
  const applyPhotoUrl = async () => {
    const url = fields.photoUrl.trim();
    if (url === lastUrlRef.current) return;
    lastUrlRef.current = url;

    if (!url) {
      setPhotoImg(null);
      setPhotoHint("ใช้รูปตั้งต้น");
      return;
    }
    try {
      const img = await loadImage(url, true);
      setPhotoImg(img);
      if (fileInputRef.current) fileInputRef.current.value = "";
      setPhotoHint("ใช้รูปจาก URL");
    } catch {
      setPhotoImg(null);
      setPhotoHint("⚠️ โหลด URL นี้ไม่ได้ (เว็บต้นทางอาจไม่อนุญาต CORS) ให้ดาวน์โหลดรูปแล้วใช้วิธีอัปโหลดแทน");
    }
  };

  const onResetPhoto = () => {
    setPhotoImg(null);
    if (fileInputRef.current) fileInputRef.current.value = "";
    setField("photoUrl", "");
    lastUrlRef.current = "";
    setPhotoHint("ใช้รูปตั้งต้น");
  };

  const onRandom = () => {
    setField("number", formatThaiId(randomThaiId()).replace(/ /g, "-"));
  };

  const fileBaseName = () => {
    const digits = fields.number.replace(/\D/g, "") || "nonumber";
    return `test-idcard-${digits}`;
  };

  const onDownloadPng = () => {
    draw();
    canvasRef.current.toBlob(blob => {
      const a = document.createElement("a");
      a.href = URL.createObjectURL(blob);
      a.download = `${fileBaseName()}.png`;
      a.click();
      URL.revokeObjectURL(a.href);
    }, "image/png");
  };

  const onDownloadPdf = async () => {
    draw();
    // โหลด jsPDF เฉพาะตอนกดดาวน์โหลด (ลดขนาด bundle หน้าแรก)
    const { jsPDF } = await import("jspdf");
    // ขนาดหน้า = ขนาดบัตรจริง 85.6 x 54 มม.
    const pdf = new jsPDF({ orientation: "landscape", unit: "mm", format: [85.6, 54] });
    pdf.addImage(canvasRef.current.toDataURL("image/png"), "PNG", 0, 0, 85.6, 54);
    pdf.save(`${fileBaseName()}.pdf`);
  };

  return (
    <section className={`container tab-panel${active ? " active" : ""}`} id="tab-idcard">
      <section className="card idcard-card">
        <div className="card-title">
          <div><span className="step">ID</span><b>Gen ID Card (ทดสอบ)</b></div>
        </div>

        <div className="idcard-layout">
          {/* ซ้าย: ฟอร์ม */}
          <div className="idcard-form">
            <label>เลขบัตรประชาชน (13 หลัก)
              <div className="idcard-row">
                <input
                  id="idcNumber" maxLength={17} placeholder="1-2345-67890-12-3"
                  value={fields.number} onChange={e => setField("number", e.target.value)}
                />
                <button id="idcRandomBtn" type="button" className="secondary" onClick={onRandom}>สุ่มเลข</button>
              </div>
              <small id="idcNumberHint">{numberHintFor(fields.number)}</small>
            </label>

            <label>ชื่อ (ไทย)       <input id="idcFirstTh" placeholder="สมชาย" value={fields.firstTh} onChange={e => setField("firstTh", e.target.value)} /></label>
            <label>นามสกุล (ไทย)    <input id="idcLastTh"  placeholder="ทดสอบ" value={fields.lastTh} onChange={e => setField("lastTh", e.target.value)} /></label>
            <label>First name (EN)  <input id="idcFirstEn" placeholder="Somchai" value={fields.firstEn} onChange={e => setField("firstEn", e.target.value)} /></label>
            <label>Last name (EN)   <input id="idcLastEn"  placeholder="Tester" value={fields.lastEn} onChange={e => setField("lastEn", e.target.value)} /></label>

            <label>รูปถ่าย: อัปโหลด
              <input id="idcPhotoFile" ref={fileInputRef} type="file" accept="image/*" onChange={onFileChange} />
            </label>
            <label>หรือวาง URL รูป
              <input
                id="idcPhotoUrl" placeholder="https://..."
                value={fields.photoUrl}
                onChange={e => setField("photoUrl", e.target.value)}
                onBlur={applyPhotoUrl}
                onKeyDown={e => { if (e.key === "Enter") applyPhotoUrl(); }}
              />
              <button id="idcResetPhotoBtn" type="button" className="secondary" onClick={onResetPhoto}>ใช้รูปตั้งต้น</button>
            </label>
            <small id="idcPhotoHint">{photoHint}</small>

            <div className="idcard-actions">
              <button id="idcPngBtn" type="button" className="primary" onClick={onDownloadPng}>⬇ ดาวน์โหลด PNG</button>
              <button id="idcPdfBtn" type="button" className="primary dark" onClick={onDownloadPdf}>⬇ ดาวน์โหลด PDF</button>
            </div>
          </div>

          {/* ขวา: ตัวอย่าง */}
          <div className="idcard-preview">
            <canvas id="idcCanvas" ref={canvasRef} width={W} height={H}></canvas>
          </div>
        </div>
      </section>
    </section>
  );
}
